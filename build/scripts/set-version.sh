#!/usr/bin/env bash
# Stamps the release version into every file that carries the app version.
# Accepts "0.1.0" or "v0.1.0"; the UI shows the v-prefixed form.
#
# Stamped:
#   services/version.go                        in-app version + update checker
#   build/config.yml                           info.version (source of the build assets)
#   build/{darwin,ios}/Info*.plist             CFBundleVersion / CFBundleShortVersionString
#   build/windows/info.json                    exe ProductVersion / FileVersion (generate:syso)
#   build/windows/nsis/wails_tools.nsh         installer VIProductVersion + DisplayVersion
#   build/windows/msix/*.xml                   MSIX package version (4-part)
#   build/windows/wails.exe.manifest           Win32 assembly version
#
# Not stamped: build/android/app/build.gradle (not part of the release pipeline,
# and versionCode has to be a monotonically increasing integer) and
# frontend/package.json (private, never shown).
set -euo pipefail

version="${1:-}"
version="${version#v}"
version="${version#V}"
if [ -z "$version" ]; then
    echo "usage: set-version.sh <version>" >&2
    exit 1
fi
# NSIS VIProductVersion and the MSIX manifests both need 4 numeric parts and
# cannot express a pre-release suffix, so only stable tags can be stamped.
if ! [[ "$version" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
    echo "set-version.sh: '$version' is not a stable X.Y.Z version" >&2
    exit 1
fi

cd "$(dirname "$0")/../.."

# GNU sed and BSD sed both accept -E and -i.bak. Each expression needs its own
# -e, otherwise sed treats the second one as an input file.
sed_i() {
    local file="$1" expr
    shift
    [ -f "$file" ] || return 0
    local args=()
    for expr in "$@"; do args+=(-e "$expr"); done
    sed -i.bak -E "${args[@]}" "$file"
    rm -f "$file.bak"
}

# Plists put the value on the line after the key, which sed cannot address
# portably, so use awk.
stamp_plist() {
    local file="$1" tmp
    [ -f "$file" ] || return 0
    tmp="$(mktemp)"
    awk -v ver="$version" '
        /<key>(CFBundleVersion|CFBundleShortVersionString)<\/key>/ { want = 1 }
        want && /<string>/ { sub(/<string>[^<]*<\/string>/, "<string>" ver "</string>"); want = 0 }
        { print }
    ' "$file" >"$tmp"
    mv "$tmp" "$file"
}

# In-app version shown on the About screen and used by the update checker.
sed_i services/version.go "s#^var Version = \".*\"#var Version = \"v${version}\"#"

# Wails build config: source for any regenerated build asset.
sed_i build/config.yml "s#^([[:space:]]*version: \")[^\"]*(\")#\1${version}\2#"

# macOS and iOS bundle versions.
for plist in \
    build/darwin/Info.plist build/darwin/Info.dev.plist \
    build/ios/Info.plist build/ios/Info.dev.plist; do
    stamp_plist "$plist"
done

# Windows exe metadata; `wails3 generate syso` embeds this into the binary.
sed_i build/windows/info.json \
    "s#(\"file_version\": \")[^\"]*(\")#\1${version}\2#" \
    "s#(\"ProductVersion\": \")[^\"]*(\")#\1${version}\2#"

# NSIS: VIProductVersion in the installer and Add/Remove Programs DisplayVersion.
# Regenerated by `wails3 task common:update:build-assets`, so re-stamp on release.
sed_i build/windows/nsis/wails_tools.nsh \
    "s#^([[:space:]]*!define INFO_PRODUCTVERSION \")[^\"]*(\")#\1${version}\2#"

# MSIX manifests need a 4-part numeric version.
for manifest in build/windows/msix/app_manifest.xml build/windows/msix/template.xml; do
    sed_i "$manifest" "s#^([[:space:]]*Version=\")[^\"]*(\")#\1${version}.0\2#"
done

# Win32 assembly manifest shipped next to the exe. Leave the Common-Controls
# dependency at its own pinned version.
sed_i build/windows/wails.exe.manifest \
    "/Microsoft.Windows.Common-Controls/!s#(<assemblyIdentity[^>]*version=\")[^\"]*#\1${version}#"

# Every file above must now contain the version; a silent no-match (a renamed
# key, a regenerated asset) would otherwise ship a build labelled 0.1.0.
targets=(
    services/version.go
    build/config.yml
    build/darwin/Info.plist
    build/darwin/Info.dev.plist
    build/ios/Info.plist
    build/ios/Info.dev.plist
    build/windows/info.json
    build/windows/nsis/wails_tools.nsh
    build/windows/msix/app_manifest.xml
    build/windows/msix/template.xml
    build/windows/wails.exe.manifest
)

failed=0
echo "Stamped version ${version}:"
for file in "${targets[@]}"; do
    [ -f "$file" ] || continue
    if grep -qF -- "$version" "$file"; then
        echo "  ok       $file"
    else
        echo "  MISSING  $file" >&2
        failed=1
    fi
done
exit "$failed"
